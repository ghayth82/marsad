"""تصنيف موضوع الادّعاء أو المادة بكلمات مفتاحية ثابتة، والمحافظات الأردنية.

التصنيف قواعد شفافة لا محرك: الصحفي يرى لماذا صُنّف الادّعاء، ووسوم الادّعاء اليدوية تسبق التصنيف الآلي.
"""

from __future__ import annotations

import re

from marsad.text import normalize_ar

TOPICS: dict[str, list[str]] = {
    "صحة": ["صحه", "مستشفي", "وباء", "فيروس", "لقاح", "دواء", "مرض", "طبيب", "كورونا", "اصابه", "اصابات", "علاج"],
    "اقتصاد": ["اقتصاد", "اسعار", "سعر", "دينار", "دولار", "بطاله", "تضخم", "ضريبه", "رواتب", "راتب", "بنك", "استثمار",
               "موازنه", "محروقات", "بنزين", "ديون", "تجاره"],
    "تعليم": ["تعليم", "مدارس", "مدرسه", "جامعه", "جامعات", "طلاب", "طلبه", "توجيهي", "امتحان", "امتحانات", "معلمين"],
    "سياسة": ["حكومه", "وزير", "وزاره", "برلمان", "نواب", "انتخابات", "رئيس الوزراء", "قانون", "مجلس"],
    "أمن": ["امن", "شرطه", "اعتقال", "جريمه", "انفجار", "حادث", "قتل", "سرقه", "مخدرات", "الامن العام"],
    "طقس وبيئة": ["طقس", "منخفض", "امطار", "ثلوج", "حراره", "زلزال", "سيول", "مياه", "جفاف", "بيئه"],
    "رياضة": ["مباراه", "منتخب", "دوري", "كره القدم", "النشامي", "بطوله", "لاعب"],
    "تقنية": ["انترنت", "تطبيق", "ذكاء اصطناعي", "اختراق", "هاكر", "منصه", "تقنيه", "رقمي"],
}
OTHER = "أخرى"

GOVERNORATES: dict[str, list[str]] = {
    "العاصمة": ["عمان", "العاصمه"],
    "إربد": ["اربد"],
    "الزرقاء": ["الزرقاء", "الزرقا"],
    "البلقاء": ["البلقاء", "السلط"],
    "مادبا": ["مادبا"],
    "الكرك": ["الكرك"],
    "الطفيلة": ["الطفيله"],
    "معان": ["معان"],
    "العقبة": ["العقبه"],
    "المفرق": ["المفرق"],
    "جرش": ["جرش"],
    "عجلون": ["عجلون"],
}

_N_TOPICS = {k: [normalize_ar(w) for w in ws] for k, ws in TOPICS.items()}
_N_GOV = {k: [normalize_ar(w) for w in ws] for k, ws in GOVERNORATES.items()}


def _has(norm: str, word: str) -> bool:
    # كلمة كاملة مع السوابق الشائعة (و، ب، ل، ال)
    return re.search(rf"(?:^|\s)(?:و|ب|ل|ف)?(?:ال)?{re.escape(word)}(?:\s|$)", norm) is not None


def topic_of(text: str, tags: list[str] | None = None) -> str:
    for t in tags or []:
        if t in TOPICS:
            return t
    norm = normalize_ar(text)
    best, score = OTHER, 0
    for topic, words in _N_TOPICS.items():
        s = sum(1 for w in words if _has(norm, w))
        if s > score:
            best, score = topic, s
    return best


def governorates_in(norm: str) -> list[str]:
    return [g for g, words in _N_GOV.items() if any(_has(norm, w) for w in words)]
